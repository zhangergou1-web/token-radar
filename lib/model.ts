// The token radar's model, version radar-2: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds
// pre-token protocols below the watchlist floor: the early rows the radar exists to find. A protocol is
// pre-token when its index entry records no token (no market cap, no CoinGecko id, no symbol); the
// snapshot's live-token protocols are kept apart and shown as the market's own values, never mixed into
// the ranked board.
//
// Implied value is a category-calibrated comparable, computed only from the snapshot's own figures:
//
//   comp     = the median mcap / TVL of the live-token protocols in the row's category, where the
//              category has at least 3 such peers; a related category's median where it has none
//              (see COMP_FALLBACK); the median over every live protocol where neither exists.
//              The multiple is clamped to [0.05, 1.5].
//   base     = tvl_usd x comp
//   growth   = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   implied  = min(3 x tvl_usd, max(1, round(base x growthMult x maturity)))
//
// A comparable is the market's own pricing: what live tokens in the same line of business trade at
// against the TVL they hold. No protocol name is ever special-cased: the same function scores every row,
// and the dashboard shows each row's comparable, its peer count and whether it fell back, so the
// derivation is checkable row by row.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

